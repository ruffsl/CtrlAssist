//! The compiled Slint UI of `ctrlassist-gui`: every component, global and
//! struct `ui/main.slint` exports, plus the translation setup tied to this
//! package's gettext domain. `ctrlassist-gui-app` re-exports it and drives it.

/// Slint's generated code, which the workspace lints don't apply to. The
/// module allows whole groups (allowing a group is fine; enabling one is
/// what the lint policy forbids) plus every warn-level rustc lint, so a
/// lint added to the workspace table later never has to revisit this.
/// Deny-level lints such as `unsafe_code` still apply, and the generated
/// code holds no `unsafe`.
mod generated {
    #![allow(
        warnings,
        clippy::restriction,
        clippy::pedantic,
        clippy::nursery,
        reason = "generated by slint-build"
    )]
    slint::include_modules!();
}

pub use generated::*;

/// The gettext domain Slint's `@tr()` and the Rust-side `gettext()` calls
/// share: this package's name, which `init_translations!` uses.
pub const GETTEXT_DOMAIN: &str = env!("CARGO_PKG_NAME");

/// Bind the gettext catalogs for Slint's `@tr()`. `init_translations!` names
/// the domain after the package it expands in, so it must expand here,
/// where the `.slint` files compile. It binds `lang/` as resolved at compile
/// time, this crate's source tree; nothing installs the catalogs yet. The
/// Rust-side `gettext()` calls also need [`GETTEXT_DOMAIN`] made the
/// process's default domain.
pub fn init_translations() {
    slint::init_translations!(concat!(env!("CARGO_MANIFEST_DIR"), "/lang"));
}
